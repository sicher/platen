#!/usr/bin/env python3
"""
Unicode canonical composition data (src/unicode_compose_data.zig), used by
src/unicode_compose.zig.

Shaping composes a base and a following combining mark into the
precomposed character when the font has a glyph for it (as HarfBuzz
does), so "i" + U+0308 renders as the designed glyph for U+00EF instead
of a dotted i with a diaeresis on top. That needs:

  pairs   every primary composite (starter, mark) -> composite, i.e. each
          canonical two-code-point decomposition that NFC recomposes
          (composition exclusions and singletons are left out)
  ccc     canonical combining class ranges (non-zero only), for NFC's
          blocking rule and the canonical-order check

Only pairs whose second code point has a non-zero combining class are
kept: those are the combining-mark compositions. (Hangul is algorithmic
and the few ccc=0 second-character pairs, e.g. Indic two-part vowels,
are not composed.)

Run with: .venv/bin/python scripts/gen_unicode_compose.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path("src/unicode_compose_data.zig")


def main():
    pairs = []
    for cp in range(sys.maxunicode + 1):
        ch = chr(cp)
        decomp = unicodedata.decomposition(ch)
        if not decomp or decomp.startswith("<"):
            continue  # none, or compatibility
        parts = [int(p, 16) for p in decomp.split()]
        if len(parts) != 2:
            continue  # singleton
        a, b = parts
        if unicodedata.combining(chr(b)) == 0:
            continue
        # Primary composite: NFC recomposes the pair (excludes exclusions)
        if unicodedata.normalize("NFC", chr(a) + chr(b)) != ch:
            continue
        pairs.append((a, b, cp))
    pairs.sort()

    ranges = []  # (first, last, ccc), consecutive code points with equal ccc
    for cp in range(sys.maxunicode + 1):
        ccc = unicodedata.combining(chr(cp))
        if ccc == 0:
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == ccc:
            ranges[-1] = (ranges[-1][0], cp, ccc)
        else:
            ranges.append((cp, cp, ccc))

    lines = [
        "//! Unicode canonical composition data (Unicode "
        + unicodedata.unidata_version + ").",
        "//! GENERATED by scripts/gen_unicode_compose.py - do not edit.",
        "",
        "/// (starter, combining mark) -> primary composite, sorted by (a, b).",
        "pub const Pair = struct { a: u21, b: u21, c: u21 };",
        "",
        "/// Consecutive code points sharing a non-zero canonical combining class.",
        "pub const CccRange = struct { first: u21, last: u21, ccc: u8 };",
        "",
        "pub const pairs = [_]Pair{",
    ]
    lines += [f"    .{{ .a = 0x{a:04X}, .b = 0x{b:04X}, .c = 0x{c:04X} }}," for a, b, c in pairs]
    lines += ["};", "", "pub const ccc_ranges = [_]CccRange{"]
    lines += [f"    .{{ .first = 0x{f:04X}, .last = 0x{l:04X}, .ccc = {c} }}," for f, l, c in ranges]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(pairs)} pairs, {len(ranges)} ccc ranges")


if __name__ == "__main__":
    main()
