/// Helper to write plain text using writeStyled
fn writeText(doc: *platen.Document, region: *platen.Region, text: []const u8, style: platen.TextStyle, opts: platen.ParagraphOptions) !platen.WriteResult {
    var st = doc.createStyledText();
    defer st.deinit();
    try st.append(text, .{});
    return doc.writeStyled(region, &st, style, opts);
}

