/// Justified text in embedded (Identity-H CID) fonts; mirrors
/// gen_justify_embedded in scripts/gen_references.py.
fn generateJustifyEmbeddedPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    const paragraphs = [_]struct { path: []const u8, text: []const u8 }{
        .{ .path = "test/fonts/Charter/Charter Regular.ttf", .text = "Typography is the art and technique of arranging type to make written " ++
            "language legible, readable, and appealing when displayed. Justified text " ++
            "creates clean edges on both sides of a text block, which many readers " ++
            "find visually appealing. The last line is typically left-aligned." },
        .{ .path = "test/fonts/Courier Prime/Courier Prime.ttf", .text = "In narrow columns, justified text requires more word spacing adjustment. " ++
            "Each line must stretch to fill the available width, which can create " ++
            "noticeable gaps between words. The last line stays ragged." },
        .{ .path = "test/fonts/Gentium/Gentium-Regular.ttf", .text = "Combining marks: re\u{0301}sume\u{0301} and cafe\u{0301} and nai\u{0308}ve and u\u{0308}ber " ++
            "and pin\u{0303}ata stretched across the line, then more ordinary words " ++
            "fill the paragraph so that several lines are justified with marks." },
    };

    try doc.addPage(.{});
    var y: f64 = 60;
    for (paragraphs) |para| {
        const font = try doc.loadFont(para.path, .identity);
        const style = platen.TextStyle{ .font = font, .size = 11 };
        // fpdf2's multi_cell puts the first baseline at top + h/2 + 0.3 * size
        // for every font; platen's .top_leading centers the font's own
        // ascender/descender in the line. Start the region where both
        // baselines coincide, so the comparison is about justification.
        const fm = doc.getFontMetricsStyled(style);
        const line_h: f64 = 11 * 1.2;
        const fpdf2_baseline = line_h / 2 + 0.3 * 11;
        const platen_baseline = (line_h + fm.ascender - @abs(fm.descender)) / 2;
        var region = platen.Region{ .x = 50, .y = y + fpdf2_baseline - platen_baseline, .width = 300, .height = 200 };
        _ = try doc.writeBlock(&region, para.text, style, .{ .alignment = .justify, .break_on_hyphens = false, .valign = .top_leading });
        y += region.cursor_y + 20;
    }

    return doc.output();
}

