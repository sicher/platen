fn generateFontCollectionPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    const ttc = try std.Io.Dir.cwd().readFileAlloc(app_io, "test/fonts/Inter/Inter.ttc", allocator, .limited(64 << 20));
    defer allocator.free(ttc); // the Document keeps its own copy of each face

    // (face index, font): Inter Regular/Bold, Inter Display Italic/Bold Italic.
    const indices = [_]u32{ 0, 14, 21, 33 };
    var faces: [indices.len]platen.Font = undefined;
    for (indices, &faces) |index, *font| font.* = try doc.loadFontFromCollection(ttc, index, .win_ansi);

    try doc.addPage(.{});
    var y: f64 = 50;
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "Font Collection (Inter.ttc)", .{ .font = faces[1], .size = 24 }, .{});
    y += 36;
    for (indices, faces) |index, font| {
        var buf: [96]u8 = undefined;
        const line = try std.fmt.bufPrint(&buf, "Face {d}: The quick brown fox jumps over the lazy dog.", .{index});
        _ = try doc.writeAt(.{ .x = 50, .y = y }, line, .{ .font = font, .size = 12 }, .{});
        y += 18;
        _ = try doc.writeAt(.{ .x = 50, .y = y }, "ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz 0123456789", .{ .font = font, .size = 12 }, .{});
        y += 26;
    }
    return doc.output();
}

fn generateCIDFontsPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    // Load fonts and set to CID (Identity-H) mode for full Unicode
    // Disable kerning to match fpdf2 reference (which uses text() without shaping)
    const charter = try doc.loadFont("test/fonts/Charter/Charter Regular.ttf", .identity);
    charter.embedded.setFeature(.kern, false);

    const courier = try doc.loadFont("test/fonts/Courier Prime/Courier Prime.ttf", .identity);
    courier.embedded.setFeature(.kern, false);

    try doc.addPage(.{});
    var y: f64 = 50;

    const charter_24 = platen.TextStyle{ .font = charter, .size = 24 };
    const charter_12 = platen.TextStyle{ .font = charter, .size = 12 };
    const courier_12 = platen.TextStyle{ .font = courier, .size = 12 };

    // Title (using CID font)
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "CID Font Test (Identity-H Encoding)", charter_24, .{});
    y += 40;

    // Basic ASCII text
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "ASCII: The quick brown fox jumps over the lazy dog.", charter_12, .{});
    y += 20;

    // UTF-8 encoded Unicode characters (Latin Extended)
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "Latin Extended: ÀÁÂÃÄÅÆÇÈÉÊË àáâãäåæçèéêë", charter_12, .{});
    y += 20;

    // More Latin characters via UTF-8
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "More Latin: Ññ Øø ß Ææ Ðð Þþ ¿¡ Œœ", charter_12, .{});
    y += 20;

    // Currency and math symbols (only those in Charter font)
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "Symbols: £ ¥ ¢ ± × ÷ ° ² ³ ¹ ¼ ½ ¾", charter_12, .{});
    y += 20;

    // Punctuation (using escape sequences for curly quotes, only those in Charter)
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "Punctuation: \xe2\x80\x98single\xe2\x80\x99 \xe2\x80\x9cdouble\xe2\x80\x9d \xe2\x80\x93 \xe2\x80\x94 \xe2\x80\xa6 \xc2\xab \xc2\xbb \xc2\xa9 \xc2\xae", charter_12, .{});
    y += 20;

    // Mixed with Courier Prime
    _ = try doc.writeAt(.{ .x = 50, .y = y }, "Courier (CID): ABCDabcd 0123456789 £¥", courier_12, .{});
    y += 24;

    // Compare with WinAnsi mode (should look the same for basic chars)
    const charter_winansi = try doc.loadFont("test/fonts/Charter/Charter Bold.ttf", .win_ansi);
    charter_winansi.embedded.setFeature(.kern, false);
    const charter_winansi_12 = platen.TextStyle{ .font = charter_winansi, .size = 12 };

    _ = try doc.writeAt(.{ .x = 50, .y = y }, "WinAnsi comparison: The quick brown fox", charter_winansi_12, .{});
    y += 20;

    _ = try doc.writeAt(.{ .x = 50, .y = y }, "CID comparison: The quick brown fox", charter_12, .{});

    return doc.output();
}

