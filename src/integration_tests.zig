const TestOptions = struct {
    skip_fonts: bool = false,
    compare_images: bool = false,
    skip_expected_images: []const usize = &.{},
    skip_actual_images: []const usize = &.{},
    truth_dir: ?[]const u8 = null,
    truth_names: []const []const u8 = &.{},
    truth_known_gaps: []const []const u8 = &.{},
};

fn runIntegrationTest(
    name: []const u8,
    generate: *const fn (std.mem.Allocator) anyerror![]u8,
) !void {
    return runIntegrationTestWithOptions(name, generate, .{});
}

fn runIntegrationTestWithOptions(
    name: []const u8,
    generate: *const fn (std.mem.Allocator) anyerror![]u8,
    options: TestOptions,
) !void {
    const allocator = std.testing.allocator;

    // Generate PDF
    const pdf = try generate(allocator);
    defer allocator.free(pdf);

    // Build paths
    var ref_path_buf: [256]u8 = undefined;
    var actual_path_buf: [256]u8 = undefined;
    var expected_path_buf: [256]u8 = undefined;
    const ref_path = std.fmt.bufPrint(&ref_path_buf, "test/reference/{s}.pdf", .{name}) catch unreachable;
    const actual_path = std.fmt.bufPrint(&actual_path_buf, "test/output/{s}_actual.pdf", .{name}) catch unreachable;
    const expected_path = std.fmt.bufPrint(&expected_path_buf, "test/output/{s}_expected.pdf", .{name}) catch unreachable;

    // Always save actual output for inspection
    std.Io.Dir.cwd().writeFile(app_io, .{ .sub_path = actual_path, .data = pdf }) catch {};

    // Copy reference to expected for side-by-side comparison (best-effort)
    if (std.Io.Dir.cwd().readFileAlloc(app_io, ref_path, allocator, .limited(50 * 1024 * 1024))) |ref_data| {
        defer allocator.free(ref_data);
        std.Io.Dir.cwd().writeFile(app_io, .{ .sub_path = expected_path, .data = ref_data }) catch {};
    } else |_| {}

    // Compare against reference
    var result = try testing.compareWithReferenceSemantic(app_io, allocator, pdf, ref_path, .{
        .skip_fonts = options.skip_fonts,
        .compare_images = options.compare_images,
        .skip_expected_images = options.skip_expected_images,
        .skip_actual_images = options.skip_actual_images,
        .truth_dir = options.truth_dir,
        .truth_names = options.truth_names,
        .truth_known_gaps = options.truth_known_gaps,
    });
    defer result.deinit();

    if (!result.equal) {
        std.debug.print("\n=== Integration test failed: {s} ===\n", .{name});
        std.debug.print("  Actual:   {s}\n", .{actual_path});
        std.debug.print("  Expected: {s}\n", .{expected_path});
        if (result.diff) |diff| {
            std.debug.print("{s}\n", .{diff});
        }
        return error.TestFailed;
    }
}

