fn generateAutoHeightPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    const title_14 = platen.TextStyle{ .font = platen.Font.helvetica, .size = 14, .bold = true };

    try doc.addPage(.{});

    // Title
    _ = try doc.writeAt(.{ .x = 50, .y = 50 }, "Auto-height Box Demo", title_14, .{});

    // Demonstrates creating a box whose height is determined by text content
    const box_width: f64 = 250;
    const box_padding: f64 = 8;

    const sample_text = "This box height is automatically calculated based on the text content. " ++
        "The text wraps within the specified width, and the box grows to fit.";

    // Measure text to get required height using write with measure_only
    var measure_region = platen.Region{
        .x = 50,
        .y = 80,
        .width = box_width,
        .height = 10000, // Large enough to fit all text for measurement
        .padding = .{ .left = box_padding, .right = box_padding, .top = box_padding, .bottom = box_padding },
    };
    const text_style = platen.TextStyle{ .font = platen.Font.helvetica, .size = 11 };
    const measure_result = try doc.write(&measure_region, sample_text, text_style, .{ .measure_only = true, .valign = .top_leading });
    // Use lines_written to calculate height with the style's font size (not stateful doc.getLineHeightPts())
    const line_height = text_style.size * 1.2; // default line_height multiplier
    const content_height = @as(f64, @floatFromInt(measure_result.lines_written)) * line_height;
    const box_height = content_height + 2 * box_padding;

    // Draw box with calculated height
    const box_y: f64 = 80;
    try doc.drawRegion(.{
        .x = 50,
        .y = box_y,
        .width = box_width,
        .height = box_height,
        .fill = platen.Color.rgbf(0.9, 0.95, 1.0),
        .border = .{ .top = true, .bottom = true, .left = true, .right = true },
    });

    // Write text inside
    var region = platen.Region{
        .x = 50,
        .y = box_y,
        .width = box_width,
        .height = box_height,
        .padding = .{ .left = box_padding, .right = box_padding, .top = box_padding, .bottom = box_padding },
    };
    _ = try doc.write(&region, sample_text, text_style, .{ .valign = .top_leading });

    return doc.output();
}

