fn generateAllFontsPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();
    try doc.addPage(.{});

    const fonts = [_]platen.StandardFont{
        .helvetica,
        .helvetica_bold,
        .helvetica_oblique,
        .helvetica_bold_oblique,
        .times_roman,
        .times_bold,
        .times_italic,
        .times_bold_italic,
        .courier,
        .courier_bold,
        .courier_oblique,
        .courier_bold_oblique,
        .symbol,
        .zapf_dingbats,
    };

    var y: f64 = 30;
    for (fonts) |font| {
        // Convert StandardFont to TextStyle
        const style: platen.TextStyle = switch (font) {
            .helvetica => .{ .font = platen.Font.helvetica, .size = 10 },
            .helvetica_bold => .{ .font = platen.Font.helvetica, .size = 10, .bold = true },
            .helvetica_oblique => .{ .font = platen.Font.helvetica, .size = 10, .italic = true },
            .helvetica_bold_oblique => .{ .font = platen.Font.helvetica, .size = 10, .bold = true, .italic = true },
            .times_roman => .{ .font = platen.Font.times, .size = 10 },
            .times_bold => .{ .font = platen.Font.times, .size = 10, .bold = true },
            .times_italic => .{ .font = platen.Font.times, .size = 10, .italic = true },
            .times_bold_italic => .{ .font = platen.Font.times, .size = 10, .bold = true, .italic = true },
            .courier => .{ .font = platen.Font.courier, .size = 10 },
            .courier_bold => .{ .font = platen.Font.courier, .size = 10, .bold = true },
            .courier_oblique => .{ .font = platen.Font.courier, .size = 10, .italic = true },
            .courier_bold_oblique => .{ .font = platen.Font.courier, .size = 10, .bold = true, .italic = true },
            .symbol => .{ .font = .symbol, .size = 10 },
            .zapf_dingbats => .{ .font = .zapf_dingbats, .size = 10 },
        };
        _ = try doc.writeAt(.{ .x = 50, .y = y }, font.pdfName(), style, .{});
        y += 15;
    }

    return doc.output();
}

