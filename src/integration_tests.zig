fn generateOpticalAlignPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    // Load fonts with different metric profiles
    const inter = try doc.loadFont("test/fonts/Inter/Inter-Regular.ttf", .identity);
    const inter_bold = try doc.loadFont("test/fonts/Inter/Inter-Bold.ttf", .identity);
    const charter = try doc.loadFont("test/fonts/Charter/Charter Regular.ttf", .identity);
    const gentium = try doc.loadFont("test/fonts/Gentium/Gentium-Regular.ttf", .identity);
    const satoshi = try doc.loadFont("test/fonts/Satoshi/Satoshi-Regular.otf", .identity);
    const courier = try doc.loadFont("test/fonts/Courier Prime/Courier Prime.ttf", .identity);

    const title_style = platen.TextStyle{ .font = inter_bold, .size = 16 };
    const subtitle_style = platen.TextStyle{ .font = inter, .size = 9, .color = platen.Color.rgb(100, 100, 100) };
    const label_style = platen.TextStyle{ .font = inter, .size = 8, .color = platen.Color.rgb(120, 120, 120) };

    const thin_stroke = platen.StrokeStyle{ .color = platen.Color.rgb(180, 180, 180), .width = 0.5 };
    const cap_stroke = platen.StrokeStyle{ .color = platen.Color.rgb(220, 60, 60), .width = 0.25, .dash = .{ .dash = 1.5, .gap = 1.5 } };
    const asc_stroke = platen.StrokeStyle{ .color = platen.Color.rgb(60, 60, 220), .width = 0.25, .dash = .{ .dash = 1.5, .gap = 1.5 } };

    const FontEntry = struct { name: []const u8, font: platen.Font };
    const test_fonts = [_]FontEntry{
        .{ .name = "Inter", .font = inter },
        .{ .name = "Charter", .font = charter },
        .{ .name = "Gentium", .font = gentium },
        .{ .name = "Satoshi", .font = satoshi },
        .{ .name = "Courier Prime", .font = courier },
    };

    try doc.addPage(.{});
    var y: f64 = 36;

    // Title
    _ = try doc.writeAt(.{ .x = 50, .y = y + 16 }, "Optical Top Alignment", title_style, .{});
    y += 26;
    _ = try doc.writeAt(.{ .x = 50, .y = y + 9 }, "VAlign: .top (cap-height)  vs  .top_ascent  vs  .top_leading (legacy)", subtitle_style, .{});
    y += 18;

    // Legend
    try doc.drawLine(.{ .x = 50, .y = y + 4 }, .{ .x = 66, .y = y + 4 }, cap_stroke);
    _ = try doc.writeAt(.{ .x = 68, .y = y + 8 }, "cap-height", .{ .font = inter, .size = 7, .color = platen.Color.rgb(220, 60, 60) }, .{});
    try doc.drawLine(.{ .x = 118, .y = y + 4 }, .{ .x = 134, .y = y + 4 }, asc_stroke);
    _ = try doc.writeAt(.{ .x = 136, .y = y + 8 }, "ascender", .{ .font = inter, .size = 7, .color = platen.Color.rgb(60, 60, 220) }, .{});
    y += 16;

    // --- Grid: 5 fonts x 3 alignments ---
    const font_size: f64 = 20;
    const box_w: f64 = 152;
    const box_h: f64 = 38;
    const col_gap: f64 = 10;
    const row_gap: f64 = 6;
    const x_start: f64 = 100;
    const sample = "Hbdgpq Ty";

    const AlignMode = struct { label: []const u8, valign: platen.VAlign };
    const modes = [_]AlignMode{
        .{ .label = ".top (cap-height)", .valign = .top },
        .{ .label = ".top_ascent", .valign = .top_ascent },
        .{ .label = ".top_leading", .valign = .top_leading },
    };

    // Column headers
    for (modes, 0..) |m, col| {
        const x = x_start + @as(f64, @floatFromInt(col)) * (box_w + col_gap);
        _ = try doc.writeAt(.{ .x = x, .y = y + 8 }, m.label, .{ .font = inter_bold, .size = 8 }, .{});
    }
    y += 14;

    for (test_fonts) |entry| {
        const style = platen.TextStyle{ .font = entry.font, .size = font_size };
        const fm = doc.getFontMetricsStyled(style);

        // Row label
        _ = try doc.writeAt(.{ .x = 50, .y = y + 14 }, entry.name, label_style, .{});

        for (modes, 0..) |m, col| {
            const x = x_start + @as(f64, @floatFromInt(col)) * (box_w + col_gap);

            // Box
            try doc.drawRect(.{ .x = x, .y = y, .width = box_w, .height = box_h }, .{ .stroke = thin_stroke });

            // Text with alignment
            var region = platen.Region{ .x = x, .y = y, .width = box_w, .height = box_h, .padding = .{ .left = 4, .right = 4 } };
            _ = try doc.write(&region, sample, style, .{ .valign = m.valign });

            // Metric guide lines (from baseline)
            const base = switch (m.valign) {
                .top => y + fm.cap_height,
                .top_ascent => y + fm.ascender,
                .top_leading => y + (font_size * 1.2 + fm.ascender - @abs(fm.descender)) / 2,
                else => y,
            };
            // Cap-height line
            try doc.drawLine(.{ .x = x, .y = base - fm.cap_height }, .{ .x = x + box_w, .y = base - fm.cap_height }, cap_stroke);
            // Ascender line
            try doc.drawLine(.{ .x = x, .y = base - fm.ascender }, .{ .x = x + box_w, .y = base - fm.ascender }, asc_stroke);
        }

        y += box_h + row_gap;
    }

    y += 8;

    // --- Section 2: Size comparison with .top ---
    _ = try doc.writeAt(.{ .x = 50, .y = y + 10 }, "Optical .top at different sizes (Inter)", .{ .font = inter_bold, .size = 10 }, .{});
    y += 18;

    const sizes = [_]f64{ 10, 14, 20, 28, 40 };
    for (sizes) |size| {
        const style = platen.TextStyle{ .font = inter, .size = size };
        const fm = doc.getFontMetricsStyled(style);
        const bh = @max(fm.cap_height + @abs(fm.descender) + 6, size * 1.2);

        try doc.drawRect(.{ .x = 100, .y = y, .width = 390, .height = bh }, .{ .stroke = thin_stroke });

        var region = platen.Region{ .x = 100, .y = y, .width = 390, .height = bh, .padding = .{ .left = 4, .right = 4 } };
        _ = try doc.write(&region, "Hbdgpq Typography", style, .{ .valign = .top });

        // Cap-height line should be at box top
        try doc.drawLine(.{ .x = 100, .y = y }, .{ .x = 490, .y = y }, cap_stroke);

        var size_buf: [16]u8 = undefined;
        const size_label = std.fmt.bufPrint(&size_buf, "{d}pt", .{size}) catch "?";
        _ = try doc.writeAt(.{ .x = 54, .y = y + 10 }, size_label, label_style, .{});

        y += bh + 4;
    }

    return doc.output();
}

