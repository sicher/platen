fn generateColorSplitPdf(allocator: std.mem.Allocator) ![]u8 {
    var doc = platen.Document.init(allocator, app_io);
    defer doc.deinit();

    // 300 distinct color emoji overflow the 255 single-byte codes of one
    // Type3 font, exercising the multi-subfont split (/Tc1 + /Tc1s1).
    const emoji = try doc.loadFont("test/fonts/Noto_Color_Emoji/NotoColorEmoji-Regular.ttf", .identity);

    const inter = try doc.loadFont("test/fonts/Inter/Inter-Regular.ttf", .identity);
    inter.embedded.setFeature(.kern, false);

    try doc.addPage(.{});
    _ = try doc.writeAt(.{ .x = 50, .y = 50 }, "300 distinct color emoji (Type3 subfont split at 255):", .{ .font = inter, .size = 12 }, .{});

    // Collect 300 codepoints with distinct color glyphs from the font's cmap.
    var row_text: std.ArrayListUnmanaged(u8) = .empty;
    defer row_text.deinit(allocator);
    var seen: std.AutoHashMapUnmanaged(u16, void) = .empty;
    defer seen.deinit(allocator);

    var y: f64 = 85;
    var cp: u21 = 0x1F300;
    while (cp <= 0x1FAFF and seen.count() < 300) : (cp += 1) {
        const gid = emoji.embedded.font.getGlyphId(cp) orelse continue;
        if (gid == 0 or !emoji.embedded.isColorGlyph(gid)) continue;
        if ((try seen.getOrPut(allocator, gid)).found_existing) continue;
        var buf: [4]u8 = undefined;
        const len = try std.unicode.utf8Encode(cp, &buf);
        try row_text.appendSlice(allocator, buf[0..len]);
        if (seen.count() % 25 == 0) { // 12 rows of 25 emoji
            _ = try doc.writeAt(.{ .x = 50, .y = y }, row_text.items, .{ .font = emoji, .size = 16 }, .{});
            row_text.clearRetainingCapacity();
            y += 22;
        }
    }

    return doc.output();
}

